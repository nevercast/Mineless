//! A 5x7 pixel font covering printable ASCII, drawn as one quad per lit pixel, so text needs no
//! font file or text-rendering crate.

pub const GLYPH_WIDTH: usize = 5;
pub const GLYPH_HEIGHT: usize = 7;

/// The bitmap for `character`, one row per byte from the top with the leftmost pixel in the
/// highest of the five low bits, or `None` outside printable ASCII.
pub fn glyph(character: char) -> Option<[u8; GLYPH_HEIGHT]> {
    let index = (character as usize).checked_sub(' ' as usize)?;
    GLYPHS.get(index).copied()
}

